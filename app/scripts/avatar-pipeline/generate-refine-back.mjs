#!/usr/bin/env node
/**
 * Second-pass targeted refinement test (Track 1, avatar-generation feature).
 *
 * Discovery: user took our prior imperfect output
 * (bon-walk-back-e2v2-1.png, a 3/4-rear view, NOT a true back view) into the
 * ChatGPT UI and simply asked "make this full back facing" -> got a clean
 * pure straight-on back view (no face/ear, hair fully covering head from
 * behind). That is a SECOND-PASS refinement of our own output, not a
 * one-shot generation from the original portrait + camera exemplar.
 *
 * This script tests whether the OpenAI images/edits API (gpt-image-1) can
 * replicate that same two-step refine technique:
 *   - Single-image edit call (NOT multi-image like the E2-v2 scripts).
 *   - Input image = our own prior flawed output, bon-walk-back-e2v2-1.png.
 *   - Prompt = simple, targeted correction mirroring what the user actually
 *     typed. No re-pasted OffshorlyChibi style-bible.
 *   - 4 independent candidates (per-call variance observed in prior tests).
 *
 * Surface generated by this script:
 *   bon-walk-back-e2v2-1.png (refine input) -> bon-walk-back-refined-{1..4}.png
 *
 * Standalone script. Not part of the Vite build. Run manually with:
 *   node scripts/avatar-pipeline/generate-refine-back.mjs
 *
 * SECURITY: never log/print process.env.OPENAI_API_KEY. Any caught error is
 * sanitized before being written to stdout/stderr so a header/request dump
 * can't leak the key.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(__dirname, "..", "..");
const ENV_PATH = path.join(APP_ROOT, ".env");
const OUTPUT_DIR = path.join(__dirname, "output");
const INPUT_IMAGE = path.join(OUTPUT_DIR, "bon-walk-back-e2v2-1.png");
const NUM_CANDIDATES = 4;
const OUT_PREFIX = "bon-walk-back-refined";

// --- minimal .env parser (no new dependency; file is 2 KEY=VALUE lines + comments) ---
function loadEnvKey(envPath, key) {
  const raw = readFileSync(envPath, "utf8");
  for (const line of raw.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const k = trimmed.slice(0, eq).trim();
    if (k === key) {
      return trimmed.slice(eq + 1).trim();
    }
  }
  return undefined;
}

/** Strip any substring equal to the secret from a string, defense-in-depth. */
function redact(str, secret) {
  if (!secret) return str;
  return str.split(secret).join("[REDACTED]");
}

// Simple, targeted prompt mirroring what the user actually typed in the
// ChatGPT UI ("make this full back facing"), expanded slightly for clarity
// but deliberately NOT re-pasting the full style-bible.
const REFINE_PROMPT =
  "Make this character fully back-facing — directly away from the camera, showing only the back of the head and hair with no face, ears, or facial features visible at all. Keep everything else (identity, clothing, pose, art style, lighting) exactly the same, just correct the camera/body orientation to a true straight-on back view.";

async function generateOne(apiKey, prompt, inputBlob, index) {
  const form = new FormData();
  form.append("model", "gpt-image-1");
  form.append("image[]", inputBlob, "bon-walk-back-e2v2-1.png");
  form.append("prompt", prompt);
  form.append("n", "1");
  form.append("size", "1024x1024");

  console.log(
    `Refine back-pose: calling OpenAI images/edits (gpt-image-1) for ${OUT_PREFIX} candidate ${index}/${NUM_CANDIDATES}...`
  );

  let res;
  try {
    res = await fetch("https://api.openai.com/v1/images/edits", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
      },
      body: form,
    });
  } catch (err) {
    const msg = redact(String(err?.message ?? err), apiKey);
    throw new Error(`Network error calling OpenAI (${OUT_PREFIX} candidate ${index}): ${msg}`);
  }

  if (!res.ok) {
    const bodyText = await res.text().catch(() => "");
    const msg = redact(bodyText, apiKey);
    throw new Error(`OpenAI API error ${res.status} (${OUT_PREFIX} candidate ${index}): ${msg}`);
  }

  const json = await res.json();
  const b64 = json?.data?.[0]?.b64_json;
  if (!b64) {
    throw new Error(
      `OpenAI response did not contain expected data[0].b64_json field (${OUT_PREFIX} candidate ${index})`
    );
  }
  return Buffer.from(b64, "base64");
}

async function main() {
  if (!existsSync(ENV_PATH)) {
    throw new Error(`.env not found at ${ENV_PATH}`);
  }
  const apiKey = loadEnvKey(ENV_PATH, "OPENAI_API_KEY");
  if (!apiKey) {
    throw new Error("OPENAI_API_KEY not found/empty in .env");
  }
  if (!existsSync(INPUT_IMAGE)) {
    throw new Error(`Refine input image not found at ${INPUT_IMAGE}`);
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });

  const inputBuffer = readFileSync(INPUT_IMAGE);
  const inputBlob = new Blob([inputBuffer], { type: "image/png" });

  const results = [];
  for (let i = 1; i <= NUM_CANDIDATES; i++) {
    const buf = await generateOne(apiKey, REFINE_PROMPT, inputBlob, i);
    const outPath = path.join(OUTPUT_DIR, `${OUT_PREFIX}-${i}.png`);
    writeFileSync(outPath, buf);
    console.log(`Refine back-pose: wrote ${OUT_PREFIX} candidate ${i} to ${outPath}`);
    results.push(outPath);
  }

  console.log(`Refine back-pose: done. Generated ${results.length} candidates in ${OUTPUT_DIR}`);
}

main().catch((err) => {
  console.error(`Refine back-pose FAILED: ${err?.message ?? err}`);
  process.exit(1);
});
